h2('3.2  六个创新点', 's3_2');
h3('3.2.1  创新点一：规则先行、模型后置的可替换智能内核');
p('三个 Agent 接口（个人推荐、管理决策、报告分析）在项目开工第一天就冻结了请求与响应形状：请求统一 `{ agent_type, target_id, context, options }`，响应统一含 `suggestion_id / suggestions / confidence / source / need_human_confirm / status`。现在后端返回的是规则算出来的结论（`source=rule`），将来模型训练好，只替换 Service 实现、把 `source` 换成 `model`，Controller、DTO、接口路径、前端页面一个字都不用改。这把「AI 能力升级」从一次系统改造降级为一次实现替换。');
h3('3.2.2  创新点二：数据库声明式 JSON 规则引擎');
p('规则存在 `rule` 表的 `condition_json` / `action_json` 两个 JSON 列里，由自研 `RuleEngine` 读库执行。条件是一棵纯数据结构树（`all` / `any` / `not` 组合器 + 叶子比较），算子限定在白名单内：比较 `eq/ne/gt/gte/lt/lte/between`、集合 `in/not_in`、文本 `contains/not_contains/contains_any/starts_with/ends_with`、布尔 `is_true/is_false/exists/missing`。**绝不使用 SpEL、eval、脚本引擎或拼接 SQL**——规则内容被当作不可信输入处理，这是电力生产系统能接受「让业务人员改规则」的前提。');
p('规则还支持「引用事实」：`action_json` 里以 `_from` 结尾的字段（如 `{"cause_from": "gas_attribution"}`）在输出时被替换成该事实的当前值。于是一条规则可以服务所有气体种类与所有档位，不必为每种气体写一条。');
h3('3.2.3  创新点三：结论可解释到数据');
